"""Render paper statistics/tables from the archived analyses; no model calls."""
from pathlib import Path
import argparse
import json

LABELS = {"qwen3_main": "Q3 11:00", "qwen3_time16": "Q3 16:00", "qwen25_main": "Q2.5 11:00"}


def percent(value):
    return f"{100*value:.1f}"


def interval(value):
    return "[" + ", ".join(percent(v) for v in value) + "]"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    project = args.project.resolve()
    out = args.out.resolve() if args.out else project / "manuscript"
    data = json.loads((project / "enhanced_analysis/robustness.json").read_text(encoding="utf-8"))
    assert data["formal_calls"] == 2040 and not data["pilots_included"]
    peers, controls = data["peer_effects"], data["control_effects"]
    assert len(peers) == 12 and len(controls) == 16
    p2 = next(r for r in peers if r["run"] == "qwen3_main" and r["persona_id"] == "P02")
    n_excludes = sum(a > 0 or b < 0 for a, b in (r["simultaneous_cp95"] for r in peers))
    assert n_excludes == 0
    text = f"""% Generated by tools/build_paper_tables.py from robustness.json.
The strengthened family-wide intervals change the interpretation of the local result (Fig.~\\ref{{fig:overview}}A). All 12 peer intervals include zero. For Qwen3 P02 at 11:00, the simultaneous interval is {interval(p2['simultaneous_cp95'])} pp, substantially wider than its pointwise interval. This conservative result does not prove no effect; it shows that the present data and family-wide criterion do not support a positive conclusion selected from all 12 contrasts.

Batch resampling gives a pointwise interval of {interval(p2['batch_bootstrap']['percentile95'])} pp for the same profile. It retains a positive local response under this grouping sensitivity, while neither addressing multiplicity nor expanding the target to human students. All 10,000 resamples for every contrast were defined. At zero-success boundaries several bootstrap intervals collapse to [0, 0]; these are empirical-support artifacts, not substitutes for binomial uncertainty.

\\begin{{figure*}}[t]
\\centering
\\includegraphics[width=\\textwidth]{{figures/robustness_overview.pdf}}
\\caption{{Peer-response audit. (A) High-minus-low valid-study differences: colored bars are original pointwise Newcombe 95\\% intervals; gray bars are conservative Clopper--Pearson/Bonferroni intervals with at least 95\\% simultaneous coverage for the complete 12-contrast peer family under the stated assumptions. (B) Seven valid actions plus invalid outputs, pooling the three equally sampled peer levels (90 completed calls per profile/run). This pooled composition is not the peer-effect estimator or the middle-level baseline. Q3 and Q2.5 denote the two fixed checkpoints.}}
\\label{{fig:overview}}
\\end{{figure*}}
"""
    rows = [r"% Generated from all 16 control contrasts; no selection.", r"\begin{table}[!ht]", r"\caption{Complete state-control contrasts in percentage points. Nominal intervals are pointwise Newcombe 95\%; simultaneous intervals use the separately defined 16-contrast control family. Low-minus-high energy targets rest; low-minus-high satiety targets eat.}", r"\label{tab:allcontrols}", r"\centering\small", r"\begin{tabular}{lllrrr}\toprule", r"Run & Profile & Target / manipulation & Difference & Pointwise 95\% & Simultaneous 95\%\\\midrule"]
    for r in controls:
        target = "rest / energy" if r["arm"] == "energy_control" else "eat / satiety"
        rows.append(f"{LABELS[r['run']]} & {r['persona_id']} & {target} & {percent(r['estimate'])} & {interval(r['original_newcombe95'])} & {interval(r['simultaneous_cp95'])}" + r"\\")
    rows += [r"\bottomrule\end{tabular}", r"\end{table}"]
    out.mkdir(parents=True, exist_ok=True)
    # Explicit bytes retain identical LF source on Windows and POSIX.
    (out / "results_enhanced.tex").write_bytes(text.encode("utf-8"))
    (out / "controls_generated.tex").write_bytes(("\n".join(rows) + "\n").encode("utf-8"))
    audit = json.loads((project / "measurement_audit/audit.json").read_text(encoding="utf-8"))
    assert audit["formal_calls"] == 2040 and not audit["study_changed_cells"]
    assert len(audit["cells"]) == 68
    assert not any(r["estimate_changed"] for r in audit["peer_effects"] + audit["control_effects"])
    rows = [r"% Generated from measurement_audit/audit.json; frozen primary retained.",
            r"\begin{table}[t]",
            r"\caption{Frozen parser versus action-only extraction. Action-only retains EOS, parseable JSON, and a legal action; auxiliary-field checks alone are relaxed. Counts cover all arms.}",
            r"\label{tab:measurement}", r"\centering\small\setlength{\tabcolsep}{3pt}",
            r"\begin{tabular}{lrrrr}\toprule",
            r"Run & Calls & Frozen & Action-only & Added\\\midrule"]
    totals = [0, 0, 0]
    for run in LABELS:
        r = audit["runs"][run]
        vals = (r["completed"], r["strict_valid"], r["action_only_valid"])
        totals = [a + b for a, b in zip(totals, vals)]
        rows.append(f"{LABELS[run]} & {vals[0]} & {vals[1]} & {vals[2]} & {vals[2]-vals[1]}" + r"\\")
    rows += [r"\midrule", f"Total & {totals[0]:,} & {totals[1]:,} & {totals[2]:,} & {totals[2]-totals[1]}" + r"\\",
             r"\bottomrule\end{tabular}", r"\end{table}"]
    (out / "measurement_generated.tex").write_bytes(("\n".join(rows) + "\n").encode("utf-8"))
    print(json.dumps({"source": "enhanced_analysis/robustness.json", "peer_contrasts": len(peers), "control_contrasts": len(controls), "simultaneous_peer_exclusions": n_excludes}))


if __name__ == "__main__":
    main()
